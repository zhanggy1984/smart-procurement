# ==================== ID 生成规则 ====================
# 全局统一 ID 前缀，MySQL / Neo4j / Milvus 共用
ID_PREFIXES = {
    "user": "U",
    "expert": "EXP",
    "supplier": "SUP",
    "project": "PRJ",
    "lot": "LOT",
    "bid": "BID",
}


def gen_id(entity: str, seq: int, width: int = 3) -> str:
    """按实体类型生成稳定 ID，如 gen_id('lot', 1) -> 'LOT-001'。"""
    prefix = ID_PREFIXES[entity]
    return f"{prefix}-{seq:0{width}d}"


