_CN_DIGIT = "一二三四五六七八"  # 章节序号中文数字（分块器标题识别只认中文数字章节）


def _chapter_heading(ch: str) -> str:
    """章节标题行：`第一章  公司概况`（必须中文数字，`第1章` 分块器不识别）。"""
    return f"第{_CN_DIGIT[int(ch) - 1]}章  {CHAPTER_NAME(ch)}"


def CHAPTER_NAME(ch: str) -> str:
    return _CHAPTER_NAMES[ch]


# 章节 -> 维度 key（评分锚定该章的维度）。模块级常量（勿与函数同名）。
CHAPTER_TO_DIM = {v: k for k, v in DIM_TO_CHAPTER.items()}


def subtopic_seq(sub_key: str) -> int:
    """子主题 key -> 全局 seq（0..23），与 chunk_id 序号一致。"""
    return SUBTOPIC_KEYS.index(sub_key)


def chunk_id_of(bid_id: str, sub_key: str) -> str:
    """GT chunk_id：f"{bid_id}-{seq:04d}"。"""
    return f"{bid_id}-{subtopic_seq(sub_key):04d}"


