def render_bid_text(bid_id: str) -> str:
    """按标书质量配置渲染 24 子主题全文（含章/子主题标题行）。

    返回文本直接交给 SmartDocumentChunker 分块，子主题顺序与 SUBTOPICS 一致。
    """
    q = QUALITY[bid_id]
    lines: list[str] = []
    cur_chapter = None
    for st in SUBTOPICS:
        if st["chapter"] != cur_chapter:
            cur_chapter = st["chapter"]
            lines.append(_chapter_heading(cur_chapter))
        quality = "medium"
        dim = CHAPTER_TO_DIM.get(cur_chapter)
        if dim:
            quality = q.get(dim, "medium")
        body = _render_subtopic(st, quality)
        lines.append(f"{st['title']}\n{body}")
    return "\n\n".join(lines)


def _render_subtopic(st: dict, quality: str) -> str:
    """单子主题正文。high/medium = 引导句 + core + (high 追加 high_extra) + 收尾句；
    low = 弱质组合（初案不成熟、依赖总集成与厂商），core 保留保证 anchor 词可检索。"""
    if quality == "low":
        return "".join([_LEAD_LOW, _LOW_PREFIX, st["core"], _LOW_SUFFIX, _TAIL["low"]])
    parts = [_LEAD[quality], st["core"]]
    if quality == "high" and st["high_extra"]:
        parts.append(st["high_extra"])
    parts.append(_TAIL[quality])
    return "".join(parts)


