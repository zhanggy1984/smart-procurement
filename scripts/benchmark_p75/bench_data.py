# ==================== AI 评分 GT 参考分 ====================
def ai_ground_truth() -> dict[str, dict[str, int]]:
    """{bid_id: {dim_key: GT 分}} = QUALITY_FACTOR[档位] × max_score，四舍五入。"""
    out: dict[str, dict[str, int]] = {}
    for bid in AI_SCORE_BIDS:
        out[bid] = {}
        for dim in DIM_ORDER:
            _, max_score, _ = DIMENSIONS[dim]
            factor = QUALITY_FACTOR[QUALITY[bid][dim]]
            out[bid][dim] = round(factor * max_score)
    return out
